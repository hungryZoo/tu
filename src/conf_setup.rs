//! tmux configuration that `tu` manages, and how it stays in sync.
//!
//! Two files are involved:
//!
//! * **`~/.config/tu/tmux.conf`** — owned by `tu`, regenerated whenever
//!   the built-in template changes. It holds the mouse / scrollback
//!   baseline, the status-bar button and its click binding.
//! * **`~/.tmux.conf`** — the user's. The only line `tu` ever adds is
//!   `source-file -q ~/.config/tu/tmux.conf`. Anything the user writes
//!   *after* that line wins (tmux keeps the last value), so overriding
//!   `tu` is a matter of placing a line below it; `tu` never touches
//!   the rest of the file.
//!
//! On launch `tu` classifies the situation ([`plan`]): nothing installed
//! yet (ask once, add the include line), a legacy `# Added by tu … #
//! End of tu` block from 1.1.x (ask once, replace it with the include
//! line), the managed file missing or out of date (rewrite silently and
//! re-source it), or up to date. The managed file is written so that
//! re-sourcing it is idempotent: the status-bar fragment is appended
//! only when `status-right` doesn't already carry it.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

/// Bump when the template below changes in a way users should get.
pub const MANAGED_VERSION: u32 = 1;

pub const LEGACY_HEADER: &str = "# Added by tu (https://github.com/hungryZoo/tu)";
pub const LEGACY_FOOTER: &str = "# End of tu";

/// The format marker that identifies our status-bar button.
pub const BUTTON_RANGE_MARKER: &str = "range=user|tu";

/// Trailing comment on the include line, used to find it again.
pub const INCLUDE_TAG: &str = "# Added by tu";

// ----------------------------------------------------------- paths

/// `~/.tmux.conf` (tmux also reads `~/.config/tmux/tmux.conf`, but the
/// classic path is what we add our line to; both are consulted when
/// looking for an existing include).
pub fn user_conf_path() -> PathBuf {
    home().join(".tmux.conf")
}

/// `$XDG_CONFIG_HOME/tu/tmux.conf`, default `~/.config/tu/tmux.conf`.
/// Deliberately not `dirs::config_dir()`: on macOS that is
/// `~/Library/Application Support`, which is a strange home for a
/// tmux snippet and awkward to type in a `source-file` line.
pub fn managed_conf_path() -> PathBuf {
    let base = std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .filter(|p| p.is_absolute())
        .unwrap_or_else(|| home().join(".config"));
    base.join("tu").join("tmux.conf")
}

fn home() -> PathBuf {
    dirs::home_dir().unwrap_or_else(|| PathBuf::from("."))
}

/// The include line as written into `~/.tmux.conf`. Uses `~` so the
/// file stays valid if the home directory moves; `-q` keeps tmux
/// quiet if the managed file is ever removed.
pub fn include_line(managed: &Path) -> String {
    let shown = match dirs::home_dir()
        .and_then(|h| managed.strip_prefix(&h).ok().map(|p| p.to_path_buf()))
    {
        Some(rel) => format!("~/{}", rel.display()),
        None => managed.display().to_string(),
    };
    format!("source-file -q {shown}  {INCLUDE_TAG}")
}

// -------------------------------------------------------- template

/// What the running tmux can do with popups.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PopupSupport {
    pub borderless: bool,
}

/// Probe the installed tmux: `None` below 3.2 (no popups at all).
pub fn detect_popup_support() -> Option<PopupSupport> {
    if !crate::tmux::supports_popup() {
        return None;
    }
    Some(PopupSupport {
        borderless: crate::tmux::supports_borderless_popup(),
    })
}

pub fn button_fragment() -> String {
    format!("#[{BUTTON_RANGE_MARKER}]#[fg=#1e1e2e,bg=#cba6f7,bold] tu #[norange]#[default]")
}

/// Status-bar click: a 60 % popup over the live panes (the same
/// default `tu` uses when launched from a pane).
pub fn popup_command(borderless: bool) -> String {
    if borderless {
        "display-popup -E -B -w 60% -h 60% tu".into()
    } else {
        "display-popup -E -w 60% -h 60% tu".into()
    }
}

/// Full contents of the managed file for this tmux.
pub fn managed_text(popup: Option<PopupSupport>) -> String {
    let mut s = String::new();
    s.push_str(&format!(
        "# tu managed tmux config v{MANAGED_VERSION} — generated by tu; edits here are overwritten.\n"
    ));
    s.push_str("# Override anything by setting it in ~/.tmux.conf *below* the source-file line.\n");
    s.push_str("set -g mouse on\n");
    s.push_str("set -g history-limit 10000000\n");
    if let Some(p) = popup {
        s.push_str("set -g status-right-length 60\n");
        // Guard: only append the button if status-right doesn't carry it
        // yet, so re-sourcing never duplicates it.
        s.push_str(&format!(
            "if -F '#{{m:*{BUTTON_RANGE_MARKER}*,#{{status-right}}}}' '' 'set -ag status-right \"{}\"'\n",
            button_fragment()
        ));
        s.push_str(&format!(
            "bind -T root MouseDown1Status if -F '#{{==:#{{mouse_status_range}},tu}}' '{}' 'select-window -t ='\n",
            popup_command(p.borderless)
        ));
    }
    s
}

// ------------------------------------------------------- detection

/// Does `text` already source our managed file?
pub fn has_include(text: &str, managed: &Path) -> bool {
    let want = include_line(managed);
    let want_path = want
        .trim_start_matches("source-file")
        .trim()
        .trim_start_matches("-q")
        .split_whitespace()
        .next()
        .unwrap_or("")
        .to_string();
    text.lines().any(|raw| {
        let l = raw.trim();
        if l.starts_with('#') || !l.starts_with("source-file") {
            return false;
        }
        l.contains(INCLUDE_TAG)
            || l.split_whitespace()
                .any(|w| w == want_path || w == managed.to_string_lossy())
    })
}

/// Byte range of a 1.1.x block (`# Added by tu` … `# End of tu`), or
/// header plus the directive lines that follow it when the footer is
/// missing (pre-1.1.0 blocks).
pub fn legacy_block(text: &str) -> Option<std::ops::Range<usize>> {
    let start = text.find(LEGACY_HEADER)?;
    // Back up to the beginning of that line.
    let start = text[..start].rfind('\n').map(|i| i + 1).unwrap_or(0);
    if let Some(f) = text[start..].find(LEGACY_FOOTER) {
        let end = start + f + LEGACY_FOOTER.len();
        let end = text[end..]
            .find('\n')
            .map(|i| end + i + 1)
            .unwrap_or(text.len());
        return Some(start..end);
    }
    // No footer: take the header line and every following non-blank line.
    let mut end = start;
    for (i, line) in text[start..].split_inclusive('\n').enumerate() {
        if i > 0 && line.trim().is_empty() {
            break;
        }
        end += line.len();
    }
    Some(start..end)
}

/// What launch should do about the tmux config.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ConfAction {
    /// Nothing of ours in `~/.tmux.conf`: ask, then add the include line.
    Install,
    /// A 1.1.x block is there: ask, then swap it for the include line.
    Migrate,
    /// Include present but the managed file is missing or stale:
    /// rewrite it without asking (it's ours) and re-source it.
    Refresh,
    UpToDate,
}

pub fn plan(user_conf: &Path, managed: &Path, popup: Option<PopupSupport>) -> ConfAction {
    let text = fs::read_to_string(user_conf).unwrap_or_default();
    if has_include(&text, managed) {
        let current = fs::read_to_string(managed).unwrap_or_default();
        return if current == managed_text(popup) {
            ConfAction::UpToDate
        } else {
            ConfAction::Refresh
        };
    }
    if legacy_block(&text).is_some() {
        ConfAction::Migrate
    } else {
        ConfAction::Install
    }
}

// --------------------------------------------------------- mutation

pub fn write_managed(managed: &Path, popup: Option<PopupSupport>) -> io::Result<()> {
    if let Some(parent) = managed.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(managed, managed_text(popup))
}

/// Append the include line to `~/.tmux.conf` (creating it if needed).
pub fn install_include(user_conf: &Path, managed: &Path) -> io::Result<()> {
    if let Some(parent) = user_conf.parent() {
        fs::create_dir_all(parent)?;
    }
    let mut text = fs::read_to_string(user_conf).unwrap_or_default();
    if has_include(&text, managed) {
        return Ok(());
    }
    if !text.is_empty() && !text.ends_with('\n') {
        text.push('\n');
    }
    if !text.is_empty() {
        text.push('\n');
    }
    text.push_str(&include_line(managed));
    text.push('\n');
    fs::write(user_conf, text)
}

/// Replace the legacy block with the include line, in place, so the
/// user's lines before and after it keep their order.
pub fn migrate_legacy(user_conf: &Path, managed: &Path) -> io::Result<()> {
    let text = fs::read_to_string(user_conf)?;
    let Some(range) = legacy_block(&text) else {
        return install_include(user_conf, managed);
    };
    let mut out = String::with_capacity(text.len());
    out.push_str(&text[..range.start]);
    out.push_str(&include_line(managed));
    out.push('\n');
    out.push_str(&text[range.end..]);
    fs::write(user_conf, out)
}

/// Make the running server match the managed file. Safe to repeat.
pub fn apply_live(managed: &Path) -> bool {
    crate::tmux::server_running() && crate::tmux::source_file(managed).ok()
}

/// Lines shown in the first-launch modal.
pub fn describe(action: &ConfAction, user_conf: &Path, managed: &Path) -> Vec<String> {
    let include = include_line(managed);
    match action {
        ConfAction::Install => vec![
            format!("{}:", shorten_home(user_conf)),
            format!("  + {include}"),
            String::new(),
            format!("{} (new, owned by tu):", shorten_home(managed)),
            "  mouse on · scrollback · status-bar tu button".into(),
        ],
        ConfAction::Migrate => vec![
            format!("{}:", shorten_home(user_conf)),
            "  - the old '# Added by tu … # End of tu' block".into(),
            format!("  + {include}"),
            String::new(),
            format!("{} (new, owned by tu):", shorten_home(managed)),
            "  mouse on · scrollback · status-bar tu button".into(),
            String::new(),
            "Edits you made inside the old block are dropped;".into(),
            "put overrides below the source-file line instead.".into(),
        ],
        ConfAction::Refresh | ConfAction::UpToDate => vec![],
    }
}

fn shorten_home(p: &Path) -> String {
    match dirs::home_dir().and_then(|h| p.strip_prefix(&h).ok().map(|r| r.to_path_buf())) {
        Some(rel) => format!("~/{}", rel.display()),
        None => p.display().to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn popup() -> Option<PopupSupport> {
        Some(PopupSupport { borderless: true })
    }

    fn write(dir: &tempfile::TempDir, name: &str, body: &str) -> PathBuf {
        let p = dir.path().join(name);
        fs::write(&p, body).unwrap();
        p
    }

    #[test]
    fn template_has_the_pieces_and_a_version() {
        let t = managed_text(popup());
        assert!(t.starts_with(&format!("# tu managed tmux config v{MANAGED_VERSION}")));
        assert!(t.contains("set -g mouse on"));
        assert!(t.contains("if -F '#{m:*range=user|tu*,#{status-right}}' '' 'set -ag status-right"));
        assert!(t.contains("display-popup -E -B -w 60% -h 60% tu"));
        let no_popup = managed_text(None);
        assert!(!no_popup.contains("status-right"));
        assert!(!no_popup.contains("bind -T root"));
        let bordered = managed_text(Some(PopupSupport { borderless: false }));
        assert!(bordered.contains("display-popup -E -w 60% -h 60% tu"));
    }

    #[test]
    fn plan_install_when_nothing_is_there() {
        let dir = tempfile::tempdir().unwrap();
        let user = write(&dir, "tmux.conf", "set -g status on\n");
        let managed = dir.path().join("tu").join("tmux.conf");
        assert_eq!(plan(&user, &managed, popup()), ConfAction::Install);
        assert_eq!(
            plan(&dir.path().join("missing"), &managed, popup()),
            ConfAction::Install
        );
    }

    #[test]
    fn plan_migrate_when_a_legacy_block_exists() {
        let dir = tempfile::tempdir().unwrap();
        let user = write(
            &dir,
            "tmux.conf",
            "set -g status on\n\n# Added by tu (https://github.com/hungryZoo/tu)\nset -g mouse on\nset -g history-limit 10000000\n# End of tu\n",
        );
        let managed = dir.path().join("tu").join("tmux.conf");
        assert_eq!(plan(&user, &managed, popup()), ConfAction::Migrate);
    }

    #[test]
    fn plan_refresh_then_up_to_date() {
        let dir = tempfile::tempdir().unwrap();
        let managed = dir.path().join("tu").join("tmux.conf");
        let user = write(&dir, "tmux.conf", &format!("{}\n", include_line(&managed)));
        assert_eq!(
            plan(&user, &managed, popup()),
            ConfAction::Refresh,
            "file missing"
        );
        fs::create_dir_all(managed.parent().unwrap()).unwrap();
        fs::write(
            &managed,
            "# tu managed tmux config v0 — old\nset -g mouse on\n",
        )
        .unwrap();
        assert_eq!(plan(&user, &managed, popup()), ConfAction::Refresh, "stale");
        write_managed(&managed, popup()).unwrap();
        assert_eq!(plan(&user, &managed, popup()), ConfAction::UpToDate);
        // A different tmux (no popups) means a different template: refresh.
        assert_eq!(plan(&user, &managed, None), ConfAction::Refresh);
    }

    #[test]
    fn include_is_found_by_tag_or_path_but_not_in_comments() {
        let managed = PathBuf::from("/home/me/.config/tu/tmux.conf");
        assert!(has_include(
            "source-file -q ~/.config/tu/tmux.conf  # Added by tu\n",
            &managed
        ));
        assert!(has_include(
            "source-file /home/me/.config/tu/tmux.conf\n",
            &managed
        ));
        assert!(!has_include(
            "# source-file -q ~/.config/tu/tmux.conf  # Added by tu\n",
            &managed
        ));
        assert!(!has_include("source-file ~/other.conf\n", &managed));
    }

    #[test]
    fn install_appends_one_line_and_is_idempotent() {
        let dir = tempfile::tempdir().unwrap();
        let managed = dir.path().join("tu").join("tmux.conf");
        let user = write(&dir, "tmux.conf", "set -g status on");
        install_include(&user, &managed).unwrap();
        install_include(&user, &managed).unwrap();
        let body = fs::read_to_string(&user).unwrap();
        assert_eq!(body.matches("source-file").count(), 1);
        assert!(body.starts_with("set -g status on\n\nsource-file -q "));
        assert!(body.ends_with(&format!("{INCLUDE_TAG}\n")));
    }

    #[test]
    fn migrate_replaces_the_block_in_place() {
        let dir = tempfile::tempdir().unwrap();
        let managed = dir.path().join("tu").join("tmux.conf");
        let user = write(
            &dir,
            "tmux.conf",
            "set -g status on\n\n# Added by tu (https://github.com/hungryZoo/tu)\nset -g mouse on\nbind -T root MouseDown1Status \\\n  if -F 'x' 'y' 'z'\n# End of tu\nset -g mouse off\n",
        );
        migrate_legacy(&user, &managed).unwrap();
        let body = fs::read_to_string(&user).unwrap();
        assert!(!body.contains("# Added by tu ("));
        assert!(!body.contains("# End of tu"));
        assert!(!body.contains("MouseDown1Status"));
        let lines: Vec<&str> = body.lines().collect();
        assert_eq!(lines[0], "set -g status on");
        assert!(lines[2].starts_with("source-file -q "));
        assert_eq!(
            lines[3], "set -g mouse off",
            "user's later override survives, in place"
        );
    }

    #[test]
    fn migrate_handles_a_footerless_block() {
        let dir = tempfile::tempdir().unwrap();
        let managed = dir.path().join("tu").join("tmux.conf");
        let user = write(
            &dir,
            "tmux.conf",
            "set -g status on\n\n# Added by tu (https://github.com/hungryZoo/tu)\nset -g mouse on\nset -g history-limit 10000000\n\nset -g base-index 1\n",
        );
        migrate_legacy(&user, &managed).unwrap();
        let body = fs::read_to_string(&user).unwrap();
        assert!(!body.contains("history-limit"));
        assert!(body.contains("set -g base-index 1"));
        assert_eq!(body.matches("source-file").count(), 1);
    }

    #[test]
    fn write_managed_creates_parents() {
        let dir = tempfile::tempdir().unwrap();
        let managed = dir.path().join("a").join("b").join("tmux.conf");
        write_managed(&managed, popup()).unwrap();
        assert_eq!(fs::read_to_string(&managed).unwrap(), managed_text(popup()));
    }

    #[test]
    fn include_line_uses_tilde_under_home() {
        if let Some(h) = dirs::home_dir() {
            let l = include_line(&h.join(".config").join("tu").join("tmux.conf"));
            assert_eq!(
                l,
                format!("source-file -q ~/.config/tu/tmux.conf  {INCLUDE_TAG}")
            );
        }
        let l = include_line(Path::new("/srv/x/tmux.conf"));
        assert!(l.starts_with("source-file -q /srv/x/tmux.conf"));
    }
}
